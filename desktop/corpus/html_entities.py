"""
Write the tables Python's html.unescape works from as Rust source:
desktop/crates/radical-io/src/html_entities.rs.

    python3 desktop/corpus/html_entities.py

html.unescape is how the reservoir ingest turns the source's `&nbsp;` cells
into text, and the port has to answer every input as Python does -- an
entity outside a hand-picked subset would read differently, silently. So the
port carries the whole HTML5 named-entity table, and the two tables of
numeric references Python special-cases, taken from the running Python
rather than retyped.
"""
import html
import html.entities
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'crates', 'radical-io', 'src', 'html_entities.rs')


def rust(text: str) -> str:
    return '"' + ''.join(c if c.isprintable() and c not in '"\\' else f'\\u{{{ord(c):x}}}'
                         for c in text) + '"'


def main() -> None:
    names = sorted(html.entities.html5.items())
    invalid_charrefs = sorted(html._invalid_charrefs.items())
    invalid_codepoints = sorted(html._invalid_codepoints)
    lines = [
        '//! Generated by desktop/corpus/html_entities.py from Python '
        f'{sys.version.split()[0]}; do not edit.',
        '//!',
        "//! The tables `html.unescape` reads: every HTML5 named reference (with",
        '//! and without its semicolon, as Python keys them), the numeric',
        '//! references it replaces, and the code points it drops.',
        '',
        '/// Name (after the `&`) -> replacement, sorted by name.',
        f'pub static NAMED: [(&str, &str); {len(names)}] = [',
        *[f'    ({rust(k)}, {rust(v)}),' for k, v in names],
        '];',
        '',
        '/// Numeric references Python replaces rather than decodes.',
        f'pub const INVALID_CHARREFS: [(u32, &str); {len(invalid_charrefs)}] = [',
        *[f'    (0x{k:x}, {rust(v)}),' for k, v in invalid_charrefs],
        '];',
        '',
        '/// Code points a numeric reference to is dropped.',
        f'pub const INVALID_CODEPOINTS: [u32; {len(invalid_codepoints)}] = [',
        *[f'    0x{k:x},' for k in invalid_codepoints],
        '];',
        '',
    ]
    with open(OUT, 'w', encoding='utf-8') as fh:
        fh.write('\n'.join(lines))
    print(f'{len(names)} names, {len(invalid_charrefs)} charrefs, '
          f'{len(invalid_codepoints)} code points -> {os.path.relpath(OUT)}')


if __name__ == '__main__':
    main()
