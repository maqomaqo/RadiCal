"""
Write NumPy's ziggurat tables for the standard normal as Rust source:
desktop/crates/radical-core/src/rng/ziggurat_tables.rs.

    cd backend && python ../desktop/corpus/ziggurat_tables.py

numpy.random.Generator.normal draws by Marsaglia and Tsang's ziggurat over
three 256-entry tables (ki_double, wi_double, fi_double in NumPy's
random/src/distributions/ziggurat_constants.h). They are data, not something
the algorithm derives at run time, so the port needs NumPy's own values to
the bit. NumPy does not ship the header in its wheels; the tables are
compiled into numpy/random/_generator, and this reads them from there --
from the NumPy that backend/requirements.txt pins, which is the one the
corpus is generated with -- and checks each looks as it must before writing.

The corpus (units/rng, `normal`) then holds the port's draws to NumPy's,
which a wrong table could not pass.
"""
import glob
import os
import struct
import sys

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'crates', 'radical-core', 'src', 'rng', 'ziggurat_tables.rs')

# The first entries, as NumPy's header has them: enough to find each table.
KI0 = 0x000EF33D8025EF6A
WI0 = 8.68362706080130616677e-16
FI1 = 9.77101701267671596263e-01


def library() -> bytes:
    root = os.path.join(os.path.dirname(np.__file__), 'random')
    found = glob.glob(os.path.join(root, '_generator.*'))
    found = [p for p in found if p.endswith(('.so', '.pyd'))]
    if len(found) != 1:
        sys.exit(f'expected one numpy/random/_generator library, found {found}')
    with open(found[0], 'rb') as fh:
        return fh.read()


def table(data: bytes, start: int, fmt: str) -> list:
    return list(struct.unpack_from('<256' + fmt, data, start))


def find_once(data: bytes, needle: bytes, what: str) -> int:
    at = data.find(needle)
    if at < 0 or data.find(needle, at + 1) >= 0:
        sys.exit(f'{what}: expected exactly one occurrence in the library')
    return at


def main() -> None:
    data = library()
    ki = table(data, find_once(data, struct.pack('<Q', KI0), 'ki_double'), 'Q')
    wi = table(data, find_once(data, struct.pack('<d', WI0), 'wi_double'), 'd')
    fi_start = find_once(data, struct.pack('<dd', 1.0, FI1), 'fi_double')
    fi = table(data, fi_start, 'd')

    # What the tables must look like. ki: 52-bit thresholds (each layer's
    # width ratio to the next, scaled by 2^52), zero only at ki[1] by
    # construction, and the first entries NumPy's header begins with. wi:
    # rising widths. fi: the density at each layer's edge, from 1 falling
    # towards 0.
    assert all(k < 1 << 52 for k in ki) and ki[1] == 0
    assert all(k > 0 for i, k in enumerate(ki) if i != 1)
    assert ki[2:4] == [0x000C08BE98FBC6A8, 0x000DA354FABD8142], 'not NumPy\'s ki_double'
    assert all(a < b for a, b in zip(wi[1:], wi[2:])), 'wi not rising'
    assert fi[0] == 1.0 and all(a > b for a, b in zip(fi, fi[1:])), 'fi not falling'
    assert 0.0 < fi[-1] < 0.01

    lines = [
        '// Generated by desktop/corpus/ziggurat_tables.py from NumPy '
        f'{np.__version__}: do not edit.',
        '//',
        "// NumPy's ziggurat tables for the standard normal (ki_double, wi_double and",
        '// fi_double in numpy/random/src/distributions/ziggurat_constants.h), read',
        '// from the compiled library. See that script, and rng::Generator::normal.',
        '',
    ]
    lines.append('pub(super) const KI: [u64; 256] = [')
    lines += [f'    0x{k:016X},' for k in ki]
    lines.append('];')
    lines.append('')
    for name, values in (('WI', wi), ('FI', fi)):
        lines.append(f'pub(super) const {name}: [f64; 256] = [')
        # repr round-trips, and Rust reads it back to the same double.
        lines += [f'    {float(v)!r},' for v in values]
        lines.append('];')
        lines.append('')
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w', encoding='utf-8') as fh:
        fh.write('\n'.join(lines))
    print(f'wrote {os.path.relpath(OUT)}')


if __name__ == '__main__':
    main()
